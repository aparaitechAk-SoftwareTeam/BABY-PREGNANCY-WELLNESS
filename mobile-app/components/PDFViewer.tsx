import React, { useState, useEffect } from 'react';
import {
  View,
  Text,
  StyleSheet,
  ScrollView,
  ActivityIndicator,
  Dimensions,
  Image,
  TouchableOpacity,
  Alert,
  Share,
} from 'react-native';
import { Download, Share2 } from 'lucide-react-native';
import * as FileSystem from 'expo-file-system/legacy';

const { width, height } = Dimensions.get('window');

interface PDFViewerProps {
  reportName: string;
  reportType: string;
}

export default function PDFViewerComponent({ reportName, reportType }: PDFViewerProps) {
  const [isLoading, setIsLoading] = useState(true);
  const [isDownloading, setIsDownloading] = useState(false);

  useEffect(() => {
    const timer = setTimeout(() => {
      setIsLoading(false);
    }, 1000);
    return () => clearTimeout(timer);
  }, []);

  const generatePDFContent = () => {
    const timestamp = new Date().toLocaleDateString();
    
    const reportData = {
      'Weekly Health Summary': {
        title: 'Weekly Health Summary',
        date: timestamp,
        sections: [
          { heading: 'Vitals Overview', content: 'Blood Pressure: 120/80 mmHg\nHeart Rate: 72 bpm\nTemperature: 98.6°F' },
          { heading: 'Activity Level', content: 'Steps: 45,230\nExercise: 4 sessions\nWater Intake: 2.5L daily' },
          { heading: 'Status', content: 'Pregnancy Week: 20\nProgress: On Track\nRecommendation: Continue current routine' },
        ],
      },
      'Pregnancy Progress Report': {
        title: 'Pregnancy Progress Report',
        date: timestamp,
        sections: [
          { heading: 'Current Status', content: 'Weeks Pregnant: 20\nEstimated Due Date: September 15, 2025' },
          { heading: 'Development Milestones', content: '• Baby size: Banana (6.5 inches)\n• Weight gain: 10-14 lbs\n• Fetal movement: Active and regular' },
          { heading: 'Health Checkup', content: 'Last Appointment: Feb 10, 2025\nNext Appointment: Feb 24, 2025\nAll tests: Normal' },
        ],
      },
      'Monthly Medical Summary': {
        title: 'Monthly Medical Summary',
        date: timestamp,
        sections: [
          { heading: 'Medical Tests', content: 'Ultrasound: Completed\nBlood Work: All Normal\nUrine Analysis: Normal' },
          { heading: 'Medications', content: 'Prenatal Vitamins: Daily\nSupplements: Iron, Calcium\nNo contraindications' },
          { heading: 'Doctor Notes', content: 'Mother is healthy and progressing well.\nNo complications noted.\nContinue regular check-ups.' },
        ],
      },
    };

    return reportData[reportName as keyof typeof reportData] || {
      title: 'Health Report',
      date: timestamp,
      sections: [{ heading: 'Overview', content: 'Standard health report content' }],
    };
  };

  const handleDownload = async () => {
    setIsDownloading(true);
    try {
      const data = generatePDFContent();
      const fileName = `${reportName.replace(/\s+/g, '_')}_${Date.now()}.txt`;
      const filePath = `${FileSystem.documentDirectory}${fileName}`;

      const content = `
APARAITECH PREGNANCY WELLNESS
Health Report
================================================================================

Report: ${data.title}
Generated: ${data.date}

================================================================================

${data.sections
  .map(
    (section) => `
${section.heading.toUpperCase()}
----------------------------------------
${section.content}
`
  )
  .join('\n')}

================================================================================
This is a confidential health report. Please keep it secure and share only with 
authorized healthcare providers.

Generated by Aparaitech Pregnancy Wellness App
================================================================================
      `;

      await FileSystem.writeAsStringAsync(filePath, content, {
        encoding: FileSystem.EncodingType.UTF8,
      });

      Alert.alert('✅ Success', `Report "${reportName}" saved to Documents!`);
    } catch (error) {
      Alert.alert('❌ Error', 'Could not save report. Please try again.');
      console.error('Download error:', error);
    } finally {
      setIsDownloading(false);
    }
  };

  const handleShare = async () => {
    try {
      const data = generatePDFContent();
      const message = `📄 ${reportName}\n\n${data.sections.map((s) => `${s.heading}\n${s.content}`).join('\n\n')}\n\nGenerated: ${data.date}`;

      await Share.share({
        message: message,
        title: reportName,
      });
    } catch (error) {
      Alert.alert('Error', 'Could not share report');
    }
  };

  const content = generatePDFContent();

  if (isLoading) {
    return (
      <View style={styles.loadingContainer}>
        <Image
          source={require('../assets/logo.png')}
          style={styles.loadingLogo}
          resizeMode="contain"
        />
        <Text style={styles.loadingText}>Loading Report...</Text>
      </View>
    );
  }

  return (
    <View style={styles.container}>
      <ScrollView 
        style={styles.scrollContainer}
        showsVerticalScrollIndicator={true}
        contentContainerStyle={styles.contentContainer}
      >
        {/* PDF Header with Logo */}
        <View style={styles.pdfHeader}>
          <Image
            source={require('../assets/logo.png')}
            style={styles.headerLogo}
            resizeMode="contain"
          />
          <Text style={styles.pdfTitle}>Aparaitech Pregnancy Wellness</Text>
          <Text style={styles.pdfSubtitle}>Health Report</Text>
          <View style={styles.divider} />
        </View>

        {/* Report Content */}
        <View style={styles.reportContent}>
          <Text style={styles.reportTitle}>{content.title}</Text>
          <Text style={styles.reportDate}>Generated: {content.date}</Text>

          {content.sections.map((section, idx) => (
            <View key={idx} style={styles.section}>
              <Text style={styles.sectionHeading}>{section.heading}</Text>
              <Text style={styles.sectionContent}>{section.content}</Text>
            </View>
          ))}

          {/* Footer */}
          <View style={styles.footer}>
            <Text style={styles.footerText}>
              This is a confidential health report. Please keep it secure and share only with authorized healthcare providers.
            </Text>
            <Text style={styles.footerNote}>
              Generated by Aparaitech Pregnancy Wellness App
            </Text>
          </View>
        </View>
      </ScrollView>

      {/* Action Buttons */}
      <View style={styles.actionBar}>
        <TouchableOpacity 
          style={[styles.actionButton, isDownloading && styles.actionButtonDisabled]}
          onPress={handleDownload}
          disabled={isDownloading}
        >
          {isDownloading ? (
            <ActivityIndicator color="#FFFFFF" size="small" />
          ) : (
            <>
              <Download size={20} color="#FFFFFF" strokeWidth={2} />
              <Text style={styles.actionButtonText}>Download</Text>
            </>
          )}
        </TouchableOpacity>
        
        <TouchableOpacity 
          style={styles.actionButton}
          onPress={handleShare}
        >
          <Share2 size={20} color="#FFFFFF" strokeWidth={2} />
          <Text style={styles.actionButtonText}>Share</Text>
        </TouchableOpacity>
      </View>
    </View>
  );
}

